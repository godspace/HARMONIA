const COMBOS = {};
const ORDER = { major: [], minor: [] };
(function parseCsv() {
  const lines = CSV.split('\n').map(l => l.trim());
  for (let i = 0; i < lines.length; i++) {
    const m = lines[i].match(/^КОМБО\s*(\d+)\s*,\s*КОМБО\s*(\d+)$/);
    if (!m) continue;
    const ids = [parseInt(m[1], 10), parseInt(m[2], 10)];
    const modes = ['major', 'minor'];
    const chords = [[], []];
    for (let r = 1; r <= 4; r++) {
      const parts = lines[i + r].split(',');
      chords[0].push(parts[0].split('-'));
      chords[1].push(parts[1].split('-'));
    }
    ids.forEach((id, k) => {
      const triads = chords[k].map(names => names.map(notePc));
      const root = triads[0][0];
      const t = chords[k][0], s = chords[k][1], d = chords[k][2];
      COMBOS[id] = {
        id, mode: modes[k], chords: chords[k], triads, root,
        keyName: cap(t[0]) + (modes[k] === 'major' ? ' мажор' : ' минор'),
        // Латинская нотация для англоязычного интерфейса: «До мажор» → «C major».
        // Считается здесь один раз, поэтому переключение P.notation ничего не
        // пересобирает — keyNameOf() просто выбирает готовую строку.
        keyNameLatin: letterNoteName(t[0]) + (modes[k] === 'major' ? ' major' : ' minor'),
        // Ступени 2 и 7 берутся из V-аккорда не по порядку: d = [V, VII, II].
        scaleNames: { 1: t[0], 2: d[2], 3: t[1], 4: s[0], 5: t[2], 6: s[1], 7: d[1] },
        third: (triads[0][1] - root + 12) % 12,
        degrees: modes[k] === 'major' ? ['I', 'IV', 'V', 'I'] : ['i', 'iv', 'V', 'i']
      };
      ORDER[modes[k]].push(id);
    });
    i += 4;
  }
})();
